import rhinoscriptsyntax as rs
import math


def 准备图层(名称, 颜色):
    if not rs.IsLayer(名称):
        rs.AddLayer(名称, 颜色)
    rs.CurrentLayer(名称)


def 生成截面曲线(层序号, 总层数, 底半径, 总扭转角, 层高, 花瓣数=5):
    """生成第 N 层的截面：一条随高度变化的光滑闭合曲线。"""
    t = 层序号 / 总层数

    # 半径随高度先收腰再张开（用余弦做出"腰身"曲线感）
    半径 = 底半径 * (0.6 + 0.4 * math.cos(t * math.pi))

    # 整层随高度旋转（扭曲塔身）
    扭转 = math.radians(总扭转角 * t)

    z = 层序号 * 层高
    点 = []
    采样 = 60
    for i in range(采样 + 1):
        a = (2 * math.pi) * (i / 采样)
        # 花瓣状起伏：半径上叠加一个正弦波动，做出未来感的褶皱轮廓
        r = 半径 * (1 + 0.15 * math.sin(花瓣数 * a))
        x = r * math.cos(a + 扭转)
        y = r * math.sin(a + 扭转)
        点.append([x, y, z])
    return rs.AddInterpCurve(点, knotstyle=3)  # 闭合周期曲线


def 建造未来建筑(总层数=24, 底半径=10, 总扭转角=120, 层高=2.5, 花瓣数=5):
    旧图层 = rs.CurrentLayer()

    # --- 1) 生成所有截面曲线 ---
    准备图层("Future_截面线", [160, 160, 160])
    截面列表 = []
    for n in range(总层数 + 1):
        截面列表.append(生成截面曲线(n, 总层数, 底半径, 总扭转角, 层高, 花瓣数))

    # --- 2) 放样成塔身表皮 ---
    准备图层("Future_塔身", [80, 180, 230])
    表皮 = rs.AddLoftSrf(截面列表)

    # --- 3) 顶部加一个封顶（取最顶截面挤一个薄盖）---
    准备图层("Future_顶冠", [255, 200, 80])
    顶截面 = 截面列表[-1]
    顶面 = rs.AddPlanarSrf(顶截面)

    # --- 4) 底座地面 ---
    准备图层("Future_地面", [180, 180, 180])
    rs.AddPlaneSurface([-底半径 * 2, -底半径 * 2, 0], 底半径 * 4, 底半径 * 4)

    rs.CurrentLayer(旧图层)
    rs.Command("_-Zoom _Extents")

    print("✅ Lesson 8 完成：未来建筑已生成！")
    print(f"   层数={总层数}, 底半径={底半径}, 扭转={总扭转角}°, 花瓣={花瓣数}")
    print(f"   截面曲线 {len(截面列表)} 条 → 放样表皮")
    print("   💡 下一步：命令行 _SaveAs 存成 .3dm，可作为课前提交文件")
    print("   💡 检查清单：单位(米/毫米)、图层是否清晰、有无重叠面")


