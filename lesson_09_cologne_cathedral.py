# Lesson 9（综合进阶）：德国科隆大教堂（参数化简化模型）
# 对应文档：第五部分示例场景「由曲线/曲面构成的建筑」
# ------------------------------------------------------------
# 用前面学过的方法，程序化搭出哥特式大教堂的关键特征：
#   - 一对高耸尖塔（收分塔身 loft + 四面锥形尖顶 SrfPt）
#   - 哥特尖拱窗（两段圆弧交于尖顶的曲线 → 平面填充）
#   - 玫瑰窗（同心圆 + 放射肋 + 花瓣小圆）
#   - 带山墙坡屋顶的中殿（盒子 + 四边面）
# 全部参数化：改顶部参数就能得到不同比例的教堂。
# ------------------------------------------------------------
# 运行方法：Rhino 8 → ScriptEditor（Python 3）→ 粘贴 → F5
# ============================================================

import rhinoscriptsyntax as rs
import math


def 准备图层(名称, 颜色):
    if not rs.IsLayer(名称):
        rs.AddLayer(名称, 颜色)
    rs.CurrentLayer(名称)


# ---------- 工具：哥特尖拱 ----------
def _弧线点(cx, cv, R, a0, a1, n):
    """在 2D(u,v) 平面采样一段圆弧。a0/a1 为角度（度）。"""
    pts = []
    for i in range(n + 1):
        t = math.radians(a0 + (a1 - a0) * i / n)
        pts.append((cx + R * math.cos(t), cv + R * math.sin(t)))
    return pts


def _尖拱点集(w, sh, n=10):
    """生成一个等边哥特尖拱的闭合轮廓（局部 u 横向 / v 竖向）。
    结构：左竖边 → 左弧 → 尖顶 → 右弧 → 右竖边 → 底边闭合。"""
    pts = [(0.0, 0.0)]
    pts += _弧线点(w, sh, w, 180, 120, n)      # 左弧：从(0,sh)升到尖顶
    pts += _弧线点(0, sh, w, 60, 0, n)[1:]      # 右弧：从尖顶降到(w,sh)
    pts += [(w, 0.0), (0.0, 0.0)]
    return pts


def 放置尖拱(基点, w, sh, 朝向="Y", 段数=10):
    """把尖拱轮廓放到世界坐标。
    朝向 'Y'：窗面朝 -Y（用于正立面）；'X'：窗面朝 X（用于侧墙）。"""
    平面点 = _尖拱点集(w, sh, 段数)
    x0, y0, z0 = 基点
    if 朝向 == "Y":
        世界点 = [[x0 + u, y0, z0 + v] for (u, v) in 平面点]
    else:  # 'X'
        世界点 = [[x0, y0 + u, z0 + v] for (u, v) in 平面点]
    return rs.AddPolyline(世界点)


# ---------- 塔楼 ----------
def 建造塔楼(x0, y0, tw, 塔身高, 尖顶高):
    """收分塔身（下大上小，loft）+ 四面锥形尖顶 + 四角小尖塔。"""
    缩 = tw * 0.12
    底 = [[x0, y0, 0], [x0 + tw, y0, 0], [x0 + tw, y0 + tw, 0],
          [x0, y0 + tw, 0], [x0, y0, 0]]
    顶角 = [[x0 + 缩, y0 + 缩, 塔身高], [x0 + tw - 缩, y0 + 缩, 塔身高],
            [x0 + tw - 缩, y0 + tw - 缩, 塔身高], [x0 + 缩, y0 + tw - 缩, 塔身高]]
    顶 = 顶角 + [顶角[0]]

    底线 = rs.AddPolyline(底)
    顶线 = rs.AddPolyline(顶)
    rs.AddLoftSrf([底线, 顶线])

    # 主尖顶：顶部四角连到一个顶点，做四个三角面
    尖点 = [x0 + tw / 2.0, y0 + tw / 2.0, 塔身高 + 尖顶高]
    for i in range(4):
        a = 顶角[i]
        b = 顶角[(i + 1) % 4]
        rs.AddSrfPt([a, b, 尖点])

    # 四角小尖塔（pinnacle）：增强哥特感
    小高 = 尖顶高 * 0.35
    小半 = tw * 0.10
    for cx, cy in [(x0 + 缩, y0 + 缩), (x0 + tw - 缩, y0 + 缩),
                   (x0 + tw - 缩, y0 + tw - 缩), (x0 + 缩, y0 + tw - 缩)]:
        角 = [[cx - 小半, cy - 小半, 塔身高], [cx + 小半, cy - 小半, 塔身高],
              [cx + 小半, cy + 小半, 塔身高], [cx - 小半, cy + 小半, 塔身高]]
        尖 = [cx, cy, 塔身高 + 小高]
        for i in range(4):
            rs.AddSrfPt([角[i], 角[(i + 1) % 4], 尖])


# ---------- 玫瑰窗 ----------
def 玫瑰窗(中心, 半径, 花瓣数=12):
    """同心圆 + 放射肋 + 一圈花瓣小圆，位于 XZ 平面（朝 -Y）。"""
    cx, cy, cz = 中心
    平面 = rs.PlaneFromNormal([cx, cy, cz], [0, 1, 0])
    rs.AddCircle(平面, 半径)            # 外圈
    rs.AddCircle(平面, 半径 * 0.30)     # 内圈花心

    for k in range(花瓣数):
        a = 2 * math.pi * k / 花瓣数
        内 = [cx + 半径 * 0.30 * math.cos(a), cy, cz + 半径 * 0.30 * math.sin(a)]
        外 = [cx + 半径 * math.cos(a), cy, cz + 半径 * math.sin(a)]
        rs.AddLine(内, 外)              # 放射肋

        # 花瓣小圆
        pcx = cx + 半径 * 0.65 * math.cos(a)
        pcz = cz + 半径 * 0.65 * math.sin(a)
        p平面 = rs.PlaneFromNormal([pcx, cy, pcz], [0, 1, 0])
        rs.AddCircle(p平面, 半径 * 0.16)


# ---------- 主程序 ----------
def 建造科隆大教堂(塔宽=8.0, 中殿宽=14.0, 中殿长=34.0,
                   墙高=20.0, 屋脊高=30.0, 塔身高=46.0, 尖顶高=34.0):
    旧图层 = rs.CurrentLayer()

    总宽 = 塔宽 * 2 + 中殿宽
    左塔x = 0.0
    右塔x = 塔宽 + 中殿宽
    殿x0 = 塔宽
    殿x1 = 塔宽 + 中殿宽
    脊x = (殿x0 + 殿x1) / 2.0

    # 1) 双塔
    准备图层("Cathedral_塔楼", [205, 195, 170])
    建造塔楼(左塔x, 0, 塔宽, 塔身高, 尖顶高)
    建造塔楼(右塔x, 0, 塔宽, 塔身高, 尖顶高)

    # 2) 中殿主体（实体盒子）
    准备图层("Cathedral_中殿", [220, 210, 185])
    殿 = [[殿x0, 0, 0], [殿x1, 0, 0], [殿x1, 中殿长, 0], [殿x0, 中殿长, 0],
          [殿x0, 0, 墙高], [殿x1, 0, 墙高], [殿x1, 中殿长, 墙高], [殿x0, 中殿长, 墙高]]
    rs.AddBox(殿)

    # 3) 坡屋顶（两块斜面 + 前后山墙三角）
    准备图层("Cathedral_屋顶", [120, 70, 60])
    rs.AddSrfPt([[殿x0, 0, 墙高], [殿x0, 中殿长, 墙高],
                 [脊x, 中殿长, 屋脊高], [脊x, 0, 屋脊高]])
    rs.AddSrfPt([[殿x1, 0, 墙高], [殿x1, 中殿长, 墙高],
                 [脊x, 中殿长, 屋脊高], [脊x, 0, 屋脊高]])
    rs.AddSrfPt([[殿x0, 0, 墙高], [殿x1, 0, 墙高], [脊x, 0, 屋脊高]])           # 前山墙
    rs.AddSrfPt([[殿x0, 中殿长, 墙高], [殿x1, 中殿长, 墙高], [脊x, 中殿长, 屋脊高]])  # 后山墙

    # 4) 玫瑰窗（正立面山墙中央）
    准备图层("Cathedral_玫瑰窗", [80, 130, 200])
    玫瑰窗([脊x, -0.05, 墙高 + 2.0], min(中殿宽, 墙高) * 0.28, 花瓣数=12)

    # 5) 正立面大门（哥特尖拱）+ 两侧小窗
    准备图层("Cathedral_门窗", [70, 110, 170])
    门宽 = 中殿宽 * 0.32
    门 = 放置尖拱([脊x - 门宽 / 2.0, -0.05, 0], 门宽, 墙高 * 0.45, 朝向="Y")
    rs.AddPlanarSrf(门)
    for off in [-中殿宽 * 0.33, 中殿宽 * 0.33]:
        w = 中殿宽 * 0.12
        c = 放置尖拱([脊x + off - w / 2.0, -0.05, 墙高 * 0.30], w, 墙高 * 0.22, 朝向="Y")
        rs.AddPlanarSrf(c)

    # 6) 中殿两侧的哥特尖拱窗（沿长度方向排布）
    准备图层("Cathedral_侧窗", [90, 140, 205])
    窗宽 = 2.4
    窗起z = 5.0
    窗高 = 4.0
    数量 = 6
    for i in range(数量):
        y = 4.0 + (中殿长 - 8.0) * i / (数量 - 1) - 窗宽 / 2.0
        左 = 放置尖拱([殿x0 - 0.05, y, 窗起z], 窗宽, 窗高, 朝向="X")
        rs.AddPlanarSrf(左)
        右 = 放置尖拱([殿x1 + 0.05, y, 窗起z], 窗宽, 窗高, 朝向="X")
        rs.AddPlanarSrf(右)

    # 7) 交叉部小尖塔（flèche，屋脊中央的小塔）
    准备图层("Cathedral_小塔", [160, 150, 130])
    建造塔楼(脊x - 2.0, 中殿长 / 2.0 - 2.0, 4.0, 屋脊高 + 4.0, 14.0)

    # 8) 地面
    准备图层("Cathedral_地面", [170, 175, 170])
    rs.AddPlaneSurface([-10, -10, -0.1], 总宽 + 20, 中殿长 + 20)

    rs.CurrentLayer(旧图层)
    rs.Command("_-Zoom _Extents")

    print("✅ Lesson 9 完成：科隆大教堂（简化参数模型）已生成！")
    print(f"   总宽={总宽:.1f}, 中殿长={中殿长}, 塔总高={塔身高 + 尖顶高:.1f}")
    print("   💡 试改参数：塔身高/尖顶高 让塔更挺拔；花瓣数 改玫瑰窗繁简")


# === 运行（改这些参数做出你自己的教堂）===
建造科隆大教堂(
    塔宽=8.0,
    中殿宽=14.0,
    中殿长=34.0,
    墙高=20.0,
    屋脊高=30.0,
    塔身高=46.0,   # 试 60 让塔更高耸
    尖顶高=34.0,   # 试 45 让尖顶更尖锐
)

# ===== 建模方法小结 =====
# 这个教堂没有用任何现成"教堂命令"，全靠基础方法拼出来：
#   收分塔身 = 两个方框 Loft（lesson_06）
#   锥形尖顶 = 四个三角面 AddSrfPt（lesson_01 曲面思想）
#   哥特尖拱 = 两段圆弧交于尖点的闭合曲线 + AddPlanarSrf（lesson_02 曲线 → 面）
#   玫瑰窗   = 同心圆 + 放射线 + 花瓣小圆（lesson_01/04）
#   坡屋顶   = 四边面 / 三角面拼接
# 这就是参数化建筑的核心：把复杂造型拆成可重复的几何单元，用函数 + 循环生成。
