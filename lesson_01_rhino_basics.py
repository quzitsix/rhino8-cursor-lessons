import rhinoscriptsyntax as rs

# Rhino 里每创建一个对象，都会返回一个 GUID（对象的唯一身份证号）。
# 我们把所有对象放到独立图层，方便检查（文档强调：图层/命名要清晰）。

def 准备图层(名称, 颜色):
    """新建图层并设为当前图层，返回旧图层名以便恢复。"""
    旧图层 = rs.CurrentLayer()
    if not rs.IsLayer(名称):
        rs.AddLayer(名称, 颜色)
    rs.CurrentLayer(名称)
    return 旧图层


def 演示基础对象():
    旧图层 = 准备图层("Lesson1_基础对象", [0, 150, 255])

    # ---- 1) 点 Point：空间中一个位置，没有长度 ----
    点 = rs.AddPoint(0, 0, 0)
    print("点 GUID:", 点)

    # ---- 2) 直线 Line：两点之间，最简单的"线对象" ----
    直线 = rs.AddLine([0, 0, 0], [10, 0, 0])
    print("直线长度:", rs.CurveLength(直线))

    # ---- 3) 曲线 Curve：经过一串点的光滑插值曲线 ----
    控制点序列 = [[0, 5, 0], [3, 8, 0], [6, 2, 0], [10, 6, 0]]
    曲线 = rs.AddInterpCurve(控制点序列)
    print("曲线长度:", round(rs.CurveLength(曲线), 2))

    # ---- 4) 曲面 Surface：一张"面"，这里用一个平面方块演示 ----
    曲面 = rs.AddPlaneSurface([0, 0, 0], 10, 10)
    print("曲面 GUID:", 曲面)

    # ---- 5) 实体 Solid：封闭的体（盒子 / 球），有体积 ----
    盒子 = rs.AddBox([
        [0, 0, 2], [10, 0, 2], [10, 10, 2], [0, 10, 2],   # 底面 4 角
        [0, 0, 8], [10, 0, 8], [10, 10, 8], [0, 10, 8],   # 顶面 4 角
    ])
    球 = rs.AddSphere([15, 5, 5], 4)
    print("盒子体积:", round(rs.SurfaceVolume(盒子)[0], 2))
    print("球体积:", round(rs.SurfaceVolume(球)[0], 2))

    rs.CurrentLayer(旧图层)
    rs.Command("_-Zoom _Extents")
    print("\n✅ Lesson 1 完成：点/线/曲线/曲面/实体 全部创建！")


演示基础对象()

# ===== 概念小结 =====
# 维度递增：点(0维) → 线/曲线(1维) → 曲面(2维) → 实体(3维)
# GUID：对象在文档里的唯一编号，几乎所有 rs 函数都靠它来操作对象。
